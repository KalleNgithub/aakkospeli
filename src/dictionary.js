// Build-time validation: each emoji word's emoji must exist in emojiMap for that letter.
for (const [letter, words] of Object.entries(dictionary)) {
  for (const entry of words) {
    if (entry.emoji && !(emojiMap[letter] ?? []).includes(entry.emoji)) {
      throw new Error(
        `Dictionary error: "${entry.word}" has emoji ${entry.emoji} ` +
        `but that emoji is not in emojiMap["${letter}"]`
      );
    }
  }
}

export function selectWord(char, displayedEmoji) {
  const letter = char.toLowerCase();
  const words = dictionary[letter];
  if (!words || words.length === 0) return null;

  const plainWords = words.filter(w => !w.emoji);
  const emojiWords = words.filter(w => w.emoji);
  const matchingEmojiWord = emojiWords.find(w => w.emoji === displayedEmoji);

  if (!matchingEmojiWord) {
    if (plainWords.length === 0) return null;
    return plainWords[Math.floor(Math.random() * plainWords.length)];
  }

  const totalWeight = plainWords.length + emojiWords.length;
  const roll = Math.floor(Math.random() * totalWeight);
  if (roll < plainWords.length) {
    return plainWords[Math.floor(Math.random() * plainWords.length)];
  }
  return matchingEmojiWord;
}
